class ProjectValues(BaseModel):
    package_name: str = Field(description="Java package, lower case, e.g. com.example.demo", pattern=PACKAGE_PATTERN)
    project_name: str = Field(description="Project name, lower case with hyphens, e.g. demo-project",
                              pattern=PROJECT_PATTERN)
    # A choice: elicitation takes only flat types, so a string with an enum - not a Literal.
    build_tool: str = Field(default="gradle", description="The build tool",
                            json_schema_extra={"enum": ["gradle", "maven"]})
    with_tests: bool = Field(default=True, description="Add a test class")


@mcp.tool(annotations=READS)
async def create_project_interactive(ctx: Context) -> list:
    """Generates a project skeleton as a ZIP archive and asks the user itself for package, project name and build
    tool (MCP elicitation) - call it without values."""
    log("create_project_interactive - asking the user")
    try:
        answer = await ctx.elicit("Which project should be generated?", ProjectValues)
    except Exception as e:  # The client did not declare elicitation, or failed.
        log(f"elicitation failed: {e}")
        return [TextContent(type="text", text=f"Could not ask the user: {e}")]
    log(f"elicitation answered: {answer.action} {getattr(answer, 'data', None)}")
    if answer.action != "accept":
        return [TextContent(type="text", text=f"The user did not give the values ({answer.action}) - nothing generated.")]
    values = answer.data
    content = project_zip(values.package_name, values.project_name)
    return [TextContent(type="text", text=f"Project {values.project_name} ({values.build_tool}, tests: "
                                          f"{values.with_tests}) generated."),
            blob(f"file:///{values.project_name}.zip", "application/zip", content)]


class Confirmation(BaseModel):
    confirm: bool = Field(description="Really delete it?")


@mcp.tool()
async def delete_item(name: str, ctx: Context) -> str:
    """Deletes an item after the server asked the user to confirm (MCP elicitation, a yes/no form)."""
    log(f"delete_item {name} - asking the user")
    try:
        answer = await ctx.elicit(f"Delete \"{name}\"? This cannot be undone.", Confirmation)
    except Exception as e:
        return f"Could not ask the user: {e}"
    if answer.action == "accept" and answer.data.confirm:
        return f"\"{name}\" deleted."
    return f"\"{name}\" kept ({answer.action})."


