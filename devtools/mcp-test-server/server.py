def project_zip(package_name: str, project_name: str, padding_mb: float = 0) -> bytes:
    """A small Java project as a ZIP archive; padding_mb adds an incompressible entry to reach a size."""
    path = package_name.replace(".", "/")
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr(f"{project_name}/README.md", f"# {project_name}\n\nGenerated by the MCP test server.\n")
        archive.writestr(f"{project_name}/src/main/java/{path}/Main.java",
                         f"package {package_name};\n\npublic class Main {{\n    public static void main(String[] args) {{\n"
                         f"        System.out.println(\"Hello from {project_name}\");\n    }}\n}}\n")
        archive.writestr(f"{project_name}/src/test/java/{path}/MainTest.java",
                         f"package {package_name};\n\nclass MainTest {{\n}}\n")
        if padding_mb > 0:
            archive.writestr(zipfile.ZipInfo(f"{project_name}/padding.bin"), os.urandom(int(padding_mb * 1024 * 1024)),
                             compress_type=zipfile.ZIP_STORED)
    return buffer.getvalue()


def png(width: int = 96, height: int = 64) -> bytes:
    """A colour gradient as PNG."""
    rows = b"".join(b"\x00" + bytes(
        channel for x in range(width) for channel in (x * 255 // width, y * 255 // height, 160)) for y in range(height))

    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))

    header = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(rows)) + chunk(b"IEND", b"")


def pdf(lines: list[str]) -> bytes:
    """A one-page PDF with these lines of text (Helvetica) - a real text layer, readable by any PDF tool."""
    text = "BT /F1 12 Tf 50 750 Td 16 TL " + " ".join(
        "(" + line.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)") + ") '" for line in lines) + " ET"
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R "
        b"/Resources << /Font << /F1 5 0 R >> >> >>",
        b"<< /Length " + str(len(text)).encode() + b" >>\nstream\n" + text.encode("latin-1") + b"\nendstream",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]
    out = io.BytesIO()
    out.write(b"%PDF-1.4\n")
    offsets = []
    for number, body in enumerate(objects, start=1):
        offsets.append(out.tell())
        out.write(f"{number} 0 obj\n".encode() + body + b"\nendobj\n")
    xref = out.tell()
    out.write(f"xref\n0 {len(objects) + 1}\n0000000000 65535 f \n".encode())
    for offset in offsets:
        out.write(f"{offset:010d} 00000 n \n".encode())
    out.write(f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode())
    return out.getvalue()


def wav(seconds: float = 0.5, rate: int = 8000) -> bytes:
    """A quiet tone as WAV."""
    samples = b"".join(struct.pack("<h", 2000 if (i // 20) % 2 else -2000) for i in range(int(seconds * rate)))
    return (b"RIFF" + struct.pack("<I", 36 + len(samples)) + b"WAVEfmt " + struct.pack("<IHHIIHH", 16, 1, 1, rate,
                                                                                      rate * 2, 2, 16)
            + b"data" + struct.pack("<I", len(samples)) + samples)


def blob(uri: str, mime_type: str | None, content: bytes) -> EmbeddedResource:
    return EmbeddedResource(type="resource", resource=BlobResourceContents(
        uri=uri, mimeType=mime_type, blob=base64.b64encode(content).decode()))


