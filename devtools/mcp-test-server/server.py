BOOKED: set[str] = set()


@mcp.tool()
def create_booking(date: str, gross: float | None = None, partner: str | None = None, number: str | None = None,
                   source: str = "", journal: str = "received") -> CallToolResult:
    """Books a document's row (a Zirmo task's call_tool step sends one per row). Carries no readOnlyHint - it
    changes something. A source booked before is refused as a repeat, the way the software must recognise a row sent
    again after a failed run."""
    log(f"create_booking {date} {gross} {partner} {number} {source} {journal}")
    if source and source in BOOKED:
        return CallToolResult(content=[TextContent(type="text", text=f"{source} is booked already - not again.")],
                              isError=True)
    if source:
        BOOKED.add(source)
    return CallToolResult(content=[TextContent(type="text", text=f"Booked {date} {gross} into {journal}.")])


