class BearerKey:
    """Refuses requests without "Authorization: Bearer <MCP_TEST_KEY>" when a key is set (plain ASGI: streams pass)."""

    def __init__(self, app, key: str):
        self.app = app
        self.key = key

    async def __call__(self, scope, receive, send):
        if self.key and scope["type"] == "http":
            headers = dict(scope.get("headers") or [])
            if headers.get(b"authorization", b"").decode() != f"Bearer {self.key}":
                await send({"type": "http.response.start", "status": 401,
                            "headers": [(b"content-type", b"text/plain")]})
                await send({"type": "http.response.body", "body": b"key missing or wrong"})
                return
        await self.app(scope, receive, send)


