@mcp.prompt(title="New project")
def new_project(package_name: str, project_name: str) -> str:
    """Generate a project with the given names - refuses values against its rules (an error, not a text)."""
    if not re.fullmatch(PACKAGE_PATTERN, package_name):
        raise ValueError(f"package_name must be lowercase and dot separated, e.g. com.example.demo: {package_name}")
    if not re.fullmatch(PROJECT_PATTERN, project_name):
        raise ValueError(f"project_name must be lowercase with hyphens, e.g. demo-project: {project_name}")
    return f"Generate the project {project_name} in the package {package_name} with the tool create_project."


