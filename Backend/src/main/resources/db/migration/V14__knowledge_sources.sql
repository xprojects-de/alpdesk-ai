-- Knowledge sources (docs/architecture/knowledge-sources.md, roadmap point 8): a folder of one of the tenant's file
-- stores, synced into the company knowledge or an area - its files become documents, changed ones are embedded again,
-- vanished ones deleted. Kept by the tenant admins and the admin. What the source saw file by file lives in the tenant
-- database (source_file).
CREATE TABLE knowledge_source
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id         BIGINT      NOT NULL REFERENCES tenant (id) ON DELETE CASCADE,
    name              TEXT        NOT NULL,
    -- A store or an area a source uses cannot be deleted (409 before, the reference behind it). No ON DELETE: the
    -- check runs at the statement's end, so deleting the tenant - which cascades to stores, areas and sources - passes.
    file_store_id     BIGINT      NOT NULL REFERENCES file_store (id),
    -- Relative to the store's folder; '' is the store's folder itself.
    folder            TEXT        NOT NULL,
    -- NULL: the company knowledge everyone finds.
    area_id           BIGINT REFERENCES knowledge_area (id),
    -- File names with * and ?; NULL: every file.
    pattern           TEXT,
    schedule          TEXT        NOT NULL CHECK (schedule IN ('MANUAL', 'HOURLY', 'EVERY_3_HOURS', 'EVERY_6_HOURS',
                                                               'EVERY_12_HOURS', 'DAILY')),
    -- Switched off: no scheduled run, its documents stay; a run by hand still works.
    active            BOOLEAN     NOT NULL,
    -- When its schedule is due next; NULL for MANUAL or switched off.
    next_run_at       TIMESTAMPTZ,
    -- The last run: when it started and ended, its error code (NULL: it worked), what it did.
    last_started_at   TIMESTAMPTZ,
    last_finished_at  TIMESTAMPTZ,
    last_error        TEXT,
    last_added        INTEGER     NOT NULL DEFAULT 0,
    last_changed      INTEGER     NOT NULL DEFAULT 0,
    last_deleted      INTEGER     NOT NULL DEFAULT 0,
    last_refused      INTEGER     NOT NULL DEFAULT 0,
    last_skipped      INTEGER     NOT NULL DEFAULT 0,
    -- The last run that listed the whole tree - "out of reach since" when runs failed after it.
    last_succeeded_at TIMESTAMPTZ,
    -- New and changed files not read yet, and their listed size: what a run by hand would read.
    open_files        INTEGER     NOT NULL DEFAULT 0,
    open_bytes        BIGINT      NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ NOT NULL,
    updated_at        TIMESTAMPTZ NOT NULL
);

CREATE UNIQUE INDEX knowledge_source_tenant_name_ci_uq ON knowledge_source (tenant_id, LOWER(name));
CREATE INDEX knowledge_source_file_store_idx ON knowledge_source (file_store_id);
CREATE INDEX knowledge_source_area_idx ON knowledge_source (area_id);
CREATE INDEX knowledge_source_due_idx ON knowledge_source (next_run_at) WHERE active;
