-- The prompts a connected software's MCP server offers (docs/architecture/mcp.md "Prompts of the connected software"):
-- read with its tools, off until a tenant admin turns them on. A user with a level for the connection picks one in the
-- chat, fills its arguments in a form, and the text the server makes of them lands in the question's input field.
CREATE TABLE mcp_prompt
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    connection_id BIGINT  NOT NULL REFERENCES mcp_connection (id) ON DELETE CASCADE,
    name          TEXT    NOT NULL,
    title         TEXT,
    description   TEXT    NOT NULL DEFAULT '',
    -- The prompt's arguments as the server gave them: a JSON list of {name, description, required}.
    arguments     TEXT    NOT NULL DEFAULT '[]',
    enabled       BOOLEAN NOT NULL DEFAULT FALSE,
    offered       BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX mcp_prompt_connection_name_uq ON mcp_prompt (connection_id, name);
