-- Several MCP keys per tenant (docs/architecture/mcp.md, roadmap point 39): each with a name, its knowledge areas and
-- the web search, composed by the admin and the tenant admins - like the client software's API keys. Until now the
-- tenant had one key, and its areas and web search were kept per tenant. The key a tenant has keeps working: it becomes
-- the key "Standard" with the tenant's areas and web search.
ALTER TABLE tenant_mcp_key DROP CONSTRAINT tenant_mcp_key_pkey;
ALTER TABLE tenant_mcp_key ADD COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;
ALTER TABLE tenant_mcp_key ADD COLUMN name TEXT NOT NULL DEFAULT 'Standard';
ALTER TABLE tenant_mcp_key ALTER COLUMN name DROP DEFAULT;
ALTER TABLE tenant_mcp_key ADD COLUMN web_search BOOLEAN NOT NULL DEFAULT FALSE;
CREATE INDEX tenant_mcp_key_tenant_idx ON tenant_mcp_key (tenant_id);

UPDATE tenant_mcp_key k
SET web_search = TRUE
WHERE EXISTS (SELECT 1 FROM tenant_mcp_web_search w WHERE w.tenant_id = k.tenant_id);

-- The areas an MCP key finds besides the company knowledge.
CREATE TABLE tenant_mcp_key_area
(
    mcp_key_id BIGINT NOT NULL REFERENCES tenant_mcp_key (id) ON DELETE CASCADE,
    area_id    BIGINT NOT NULL REFERENCES knowledge_area (id) ON DELETE CASCADE,
    PRIMARY KEY (mcp_key_id, area_id)
);
CREATE INDEX tenant_mcp_key_area_area_idx ON tenant_mcp_key_area (area_id);

INSERT INTO tenant_mcp_key_area (mcp_key_id, area_id)
SELECT k.id, a.area_id
FROM tenant_mcp_key k
         JOIN tenant_mcp_area a ON a.tenant_id = k.tenant_id;

-- A tenant without a key loses only settings no key used; the next key is composed anew.
DROP TABLE tenant_mcp_area;
DROP TABLE tenant_mcp_web_search;

-- The connected software each MCP key may use (roadmap point 41), chosen per key like its areas - through
-- ask_assistant and, where the connection allows it, directly. It replaces the connection's switch for the MCP server
-- (mcp_server_reads): every key gets every connection that switch had opened, then the switch goes.
CREATE TABLE tenant_mcp_key_connection
(
    mcp_key_id    BIGINT NOT NULL REFERENCES tenant_mcp_key (id) ON DELETE CASCADE,
    connection_id BIGINT NOT NULL REFERENCES mcp_connection (id) ON DELETE CASCADE,
    PRIMARY KEY (mcp_key_id, connection_id)
);
CREATE INDEX tenant_mcp_key_connection_connection_idx ON tenant_mcp_key_connection (connection_id);

INSERT INTO tenant_mcp_key_connection (mcp_key_id, connection_id)
SELECT k.id, c.id
FROM tenant_mcp_key k
         JOIN mcp_connection c ON c.tenant_id = k.tenant_id AND c.mcp_server_reads;

ALTER TABLE mcp_connection DROP COLUMN mcp_server_reads;

-- Whether a key with the connection gets its reading tools, prompts and instructions directly ("Direkt an
-- MCP-Clients") - off: answers through ask_assistant only, a licensed module's knowledge stays behind the assistant.
ALTER TABLE mcp_connection ADD COLUMN passes_through BOOLEAN NOT NULL DEFAULT FALSE;

-- The instructions the server gives in its initialize - how its tools go together - read with its tools, cut to
-- 2,000 characters; null when it gives none.
ALTER TABLE mcp_connection ADD COLUMN instructions TEXT;

-- The scheduled tasks an MCP key may list, start and read the runs of (list_tasks, run_task, task_run) - chosen per
-- key like the API keys' tenant_api_key_task, instead of one switch per task for every key (open_to_mcp).
CREATE TABLE tenant_mcp_key_task
(
    mcp_key_id BIGINT NOT NULL REFERENCES tenant_mcp_key (id) ON DELETE CASCADE,
    task_id    BIGINT NOT NULL REFERENCES task (id) ON DELETE CASCADE,
    PRIMARY KEY (mcp_key_id, task_id)
);

CREATE INDEX tenant_mcp_key_task_task_idx ON tenant_mcp_key_task (task_id);

-- Every key keeps the tasks opened to the MCP server so far.
INSERT INTO tenant_mcp_key_task (mcp_key_id, task_id)
SELECT k.id, t.id
FROM tenant_mcp_key k
         JOIN task t ON t.tenant_id = k.tenant_id AND t.open_to_mcp;

ALTER TABLE task DROP COLUMN open_to_mcp;

-- The connected software each API key of the client software may use through /api/v1/chat (roadmap point 42), chosen
-- per key like its areas and tasks - instead of one switch per connection for every key (client_software_reads).
CREATE TABLE tenant_api_key_connection
(
    api_key_id    BIGINT NOT NULL REFERENCES tenant_api_key (id) ON DELETE CASCADE,
    connection_id BIGINT NOT NULL REFERENCES mcp_connection (id) ON DELETE CASCADE,
    PRIMARY KEY (api_key_id, connection_id)
);

CREATE INDEX tenant_api_key_connection_connection_idx ON tenant_api_key_connection (connection_id);

-- Every key keeps the connections opened to the client software so far.
INSERT INTO tenant_api_key_connection (api_key_id, connection_id)
SELECT k.id, c.id
FROM tenant_api_key k
         JOIN mcp_connection c ON c.tenant_id = k.tenant_id AND c.client_software_reads;

ALTER TABLE mcp_connection DROP COLUMN client_software_reads;
