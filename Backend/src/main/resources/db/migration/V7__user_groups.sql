-- User groups (docs/architecture/tenancy.md "User groups"): a tenant user's level for a connected software and the
-- knowledge areas it finds come from its groups - no longer from rights of its own. Several groups: the highest level
-- of all of them counts, and the union of their areas. A user in no group has the base every user has: the chat and
-- the company knowledge.
CREATE TABLE user_group
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  BIGINT      NOT NULL REFERENCES tenant (id) ON DELETE CASCADE,
    name       TEXT        NOT NULL,
    -- With a WAM proxy that sends the person's IDM groups (app.wam.groups-header): membership counts only while the
    -- proxy lists this IDM group. NULL: membership counts as it is.
    wam_group  TEXT,
    created_at TIMESTAMPTZ NOT NULL
);
CREATE UNIQUE INDEX user_group_name_ci_uq ON user_group (tenant_id, LOWER(name));

CREATE TABLE user_group_member
(
    group_id BIGINT NOT NULL REFERENCES user_group (id) ON DELETE CASCADE,
    user_id  BIGINT NOT NULL REFERENCES tenant_user (id) ON DELETE CASCADE,
    PRIMARY KEY (group_id, user_id)
);
CREATE INDEX user_group_member_user_idx ON user_group_member (user_id);

-- READ - the connection's reading tools that are turned on; WRITE - all its tools that are turned on. No row: no access.
CREATE TABLE group_mcp_access
(
    group_id      BIGINT NOT NULL REFERENCES user_group (id) ON DELETE CASCADE,
    connection_id BIGINT NOT NULL REFERENCES mcp_connection (id) ON DELETE CASCADE,
    level         TEXT   NOT NULL CHECK (level IN ('READ', 'WRITE')),
    PRIMARY KEY (group_id, connection_id)
);
CREATE INDEX group_mcp_access_connection_idx ON group_mcp_access (connection_id);

CREATE TABLE group_area
(
    group_id BIGINT NOT NULL REFERENCES user_group (id) ON DELETE CASCADE,
    area_id  BIGINT NOT NULL REFERENCES knowledge_area (id) ON DELETE CASCADE,
    PRIMARY KEY (group_id, area_id)
);
CREATE INDEX group_area_area_idx ON group_area (area_id);

-- The IDM groups the WAM proxy sent on the user's last request, lower case - written when they change.
CREATE TABLE tenant_user_wam_group
(
    user_id BIGINT NOT NULL REFERENCES tenant_user (id) ON DELETE CASCADE,
    name    TEXT   NOT NULL,
    PRIMARY KEY (user_id, name)
);

-- The rights per user are not carried over (decided 16 October 2026): after the update a tenant admin creates the
-- groups and assigns the users - until then a user has the chat and the company knowledge.
DROP TABLE mcp_access;
DROP TABLE tenant_user_area;
