-- Knowledge areas (docs/architecture/ai-features.md "Knowledge areas"): a tenant's documents are its company knowledge,
-- found by everyone, unless they belong to an area - those only the users and keys assigned to it find (tenant admins
-- find every area). A document's area is kept in its tenant database (document.area_id); who may read an area is kept
-- here, next to the users and keys.
CREATE TABLE knowledge_area
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  BIGINT      NOT NULL REFERENCES tenant (id) ON DELETE CASCADE,
    name       TEXT        NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);
CREATE UNIQUE INDEX knowledge_area_name_ci_uq ON knowledge_area (tenant_id, LOWER(name));

-- The areas a tenant user finds besides the company knowledge.
CREATE TABLE tenant_user_area
(
    user_id BIGINT NOT NULL REFERENCES tenant_user (id) ON DELETE CASCADE,
    area_id BIGINT NOT NULL REFERENCES knowledge_area (id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, area_id)
);
CREATE INDEX tenant_user_area_area_idx ON tenant_user_area (area_id);

-- The areas a client software's API key finds (/api/v1/chat) and may push documents into (/api/v1/documents).
CREATE TABLE tenant_api_key_area
(
    api_key_id BIGINT NOT NULL REFERENCES tenant_api_key (id) ON DELETE CASCADE,
    area_id    BIGINT NOT NULL REFERENCES knowledge_area (id) ON DELETE CASCADE,
    PRIMARY KEY (api_key_id, area_id)
);
CREATE INDEX tenant_api_key_area_area_idx ON tenant_api_key_area (area_id);

-- The areas the tenant's MCP server finds (ask_assistant) - kept per tenant, not per key: a new MCP key keeps them.
CREATE TABLE tenant_mcp_area
(
    tenant_id BIGINT NOT NULL REFERENCES tenant (id) ON DELETE CASCADE,
    area_id   BIGINT NOT NULL REFERENCES knowledge_area (id) ON DELETE CASCADE,
    PRIMARY KEY (tenant_id, area_id)
);
CREATE INDEX tenant_mcp_area_area_idx ON tenant_mcp_area (area_id);
