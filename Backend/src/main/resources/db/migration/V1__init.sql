-- Initial schema of the management database (PostgreSQL). Every later schema change is a new
-- V<n>__<description>.sql file; an applied migration is never edited afterwards (until the first production
-- installation this file may still be extended - a database created from an older one must then be recreated). A
-- tenant's own data (documents, embeddings, chat history) lives in its own database - see docs/architecture/tenancy.md.

-- The AI models the tenants may use, maintained by the admin with the prices billed for them
-- (docs/architecture/ai-features.md). Prices per million tokens, in the currency the admin bills.
CREATE TABLE ai_model
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider           TEXT          NOT NULL CHECK (provider IN ('ANTHROPIC', 'OPENAI', 'GEMINI', 'OLLAMA', 'OPENAI_COMPATIBLE')),
    kind               TEXT          NOT NULL CHECK (kind IN ('CHAT', 'EMBEDDING')),
    model_name         TEXT          NOT NULL,
    display_name       TEXT          NOT NULL,
    -- The vector length of an embedding model (the tenant's embedding table is created with it); NULL for chat models.
    dimension          INTEGER CHECK (dimension > 0),
    input_price        NUMERIC(12, 4) NOT NULL CHECK (input_price >= 0),
    output_price       NUMERIC(12, 4) NOT NULL CHECK (output_price >= 0),
    -- What a chat model reads as it is (docs/architecture/ai-features.md "Files in the chat"): images every chat model
    -- reads; PDFs, audio and video only some - the tool read_file sends the original file only to a model that reads it.
    reads_pdf          BOOLEAN       NOT NULL DEFAULT FALSE,
    reads_audio        BOOLEAN       NOT NULL DEFAULT FALSE,
    reads_video        BOOLEAN       NOT NULL DEFAULT FALSE,
    -- The one chat model (reading audio) that writes the transcript of an uploaded audio file - so a model that cannot
    -- listen can still read it.
    transcribes        BOOLEAN       NOT NULL DEFAULT FALSE,
    -- The one chat model that reads the images and scanned pages of the company's documents before they are embedded
    -- (docs/architecture/ai-features.md "Images and scans") - every chat model reads images.
    reads_scans        BOOLEAN       NOT NULL DEFAULT FALSE,
    -- What a chat model is sent of the tenant's settings (docs/architecture/ai-features.md "Assistant settings and
    -- templates"): a temperature (reasoning models refuse one), and the reasoning effort.
    takes_temperature  BOOLEAN       NOT NULL DEFAULT TRUE,
    steers_reasoning   BOOLEAN       NOT NULL DEFAULT FALSE,
    -- Whether a chat model calls tools reliably; without, the chat searches and reads the files for it beforehand.
    calls_tools        BOOLEAN       NOT NULL DEFAULT TRUE,
    -- OLLAMA and OPENAI_COMPATIBLE run on a server the admin enters here (docs/architecture/ai-features.md "Own model
    -- servers"): its address, and its key if it asks for one - encrypted like the provider keys, never sent out again.
    base_url           TEXT,
    api_key            TEXT,
    key_hint           TEXT,
    -- OLLAMA chat models: the context length sent with every request (num_ctx) - Ollama cuts off silently beyond it.
    context_length     INTEGER CHECK (context_length > 0),
    -- Chat models: the most tokens one answer may take, reasoning included (a model that thinks spends its output on
    -- it first); NULL = app.ai.max-output-tokens. A thinking budget the tenant chose comes on top.
    max_output_tokens  INTEGER CHECK (max_output_tokens > 0),
    active             BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at         TIMESTAMPTZ   NOT NULL,
    updated_at         TIMESTAMPTZ   NOT NULL,
    CHECK ((kind = 'EMBEDDING') = (dimension IS NOT NULL)),
    CONSTRAINT ai_model_transcriber_reads_audio CHECK (NOT transcribes OR (kind = 'CHAT' AND reads_audio)),
    CONSTRAINT ai_model_scan_reader_chat CHECK (NOT reads_scans OR kind = 'CHAT'),
    CONSTRAINT ai_model_server CHECK ((provider IN ('OLLAMA', 'OPENAI_COMPATIBLE')) = (base_url IS NOT NULL)),
    CONSTRAINT ai_model_key_hint CHECK ((api_key IS NULL) = (key_hint IS NULL) AND (api_key IS NULL OR base_url IS NOT NULL)),
    CONSTRAINT ai_model_context_length CHECK (context_length IS NULL OR (provider = 'OLLAMA' AND kind = 'CHAT'))
);
-- The same model name may run on several servers.
CREATE UNIQUE INDEX ai_model_provider_kind_name_uq ON ai_model (provider, kind, model_name, COALESCE(base_url, ''));
CREATE UNIQUE INDEX ai_model_one_transcriber_uq ON ai_model (transcribes) WHERE transcribes;
CREATE UNIQUE INDEX ai_model_one_scan_reader_uq ON ai_model (reads_scans) WHERE reads_scans;

-- A tenant (Mandant): one customer of Alpdesk AI, a company of any trade. Tenant isolation is always derived from the
-- authenticated tenant, never from request input.
CREATE TABLE tenant
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT        NOT NULL,
    active        BOOLEAN     NOT NULL DEFAULT TRUE,
    contact_email TEXT,
    notes         TEXT,
    -- The tenant's own database on the same PostgreSQL server (docs/architecture/tenancy.md). The random part keeps a
    -- database left behind by a deleted tenant from ever being taken over by a new one.
    database_name TEXT        NOT NULL UNIQUE,
    -- Whether the tenant may use the admin's API keys where it has none of its own (the usage is then billed).
    global_keys_allowed BOOLEAN NOT NULL DEFAULT FALSE,
    -- The one model its documents are embedded with (chosen by an admin); changing it embeds every document again.
    embedding_model_id BIGINT REFERENCES ai_model (id),
    created_at    TIMESTAMPTZ NOT NULL,
    updated_at    TIMESTAMPTZ NOT NULL
);
CREATE UNIQUE INDEX tenant_name_ci_uq ON tenant (LOWER(name));

-- The client software's keys for /api/v1 (created by the admin or a tenant admin). Only the SHA-256 hash is stored; the key itself is shown once on creation.
CREATE TABLE tenant_api_key
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    BIGINT      NOT NULL REFERENCES tenant (id) ON DELETE CASCADE,
    name         TEXT        NOT NULL,
    key_prefix   TEXT        NOT NULL,
    key_hash     TEXT        NOT NULL UNIQUE,
    -- False: the key's chat questions are answered and forgotten - no conversation, no message, no file is stored,
    -- only the usage (a client software that sends logs to be checked again and again).
    keeps_history BOOLEAN    NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMPTZ NOT NULL,
    last_used_at TIMESTAMPTZ
);
CREATE INDEX tenant_api_key_tenant_idx ON tenant_api_key (tenant_id);

-- The tenant's one key for its MCP server (docs/architecture/mcp.md): an MCP client - Claude Code - asks the tenant's
-- assistant with it, like a user who sees no documents. Nothing else is reached with it. Only the SHA-256 hash is
-- stored; a new key replaces the previous one.
CREATE TABLE tenant_mcp_key
(
    tenant_id    BIGINT PRIMARY KEY REFERENCES tenant (id) ON DELETE CASCADE,
    key_prefix   TEXT        NOT NULL,
    key_hash     TEXT        NOT NULL UNIQUE,
    created_at   TIMESTAMPTZ NOT NULL,
    last_used_at TIMESTAMPTZ
);

-- A tenant's employees, who log into the frontend and chat. Created by the admin or a tenant admin. The username is
-- unique across all tenants: the login has no tenant field.
CREATE TABLE tenant_user
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT      NOT NULL REFERENCES tenant (id) ON DELETE CASCADE,
    username      TEXT        NOT NULL,
    display_name  TEXT        NOT NULL,
    -- PBKDF2 (security.PasswordHasher), never the password itself. NULL: the user signs in through the WAM proxy only
    -- (security.WamProxy) and has no password.
    password_hash TEXT,
    active        BOOLEAN     NOT NULL DEFAULT TRUE,
    -- A tenant admin keeps the tenant's settings (users, API keys, embedding model, company knowledge, usage) and
    -- chats like every user (docs/architecture/tenancy.md "Who does what").
    admin         BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMPTZ NOT NULL,
    updated_at    TIMESTAMPTZ NOT NULL,
    last_login_at TIMESTAMPTZ,
    -- Tokens issued before this moment are refused (security.ActiveTenantUserRule) - set when an admin sets a new
    -- password, so a misused session ends with it. Whole seconds, like a JWT's "iat".
    sessions_valid_from TIMESTAMPTZ
);
CREATE UNIQUE INDEX tenant_user_username_ci_uq ON tenant_user (LOWER(username));
CREATE INDEX tenant_user_tenant_idx ON tenant_user (tenant_id);

-- Someone the WAM proxy let through who is no tenant user yet (security.WamProxy, docs/architecture/tenancy.md "Sign-in
-- through a WAM proxy"): the admin assigns the request to a tenant - which makes it a tenant user without a password -
-- or rejects it. One per username.
CREATE TABLE access_request
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username     TEXT        NOT NULL,
    display_name TEXT        NOT NULL,
    requested_at TIMESTAMPTZ NOT NULL
);
CREATE UNIQUE INDEX access_request_username_ci_uq ON access_request (LOWER(username));

-- The AI providers' API keys: a tenant's own (tenant_id set, entered by an admin) or the admin's global ones
-- (tenant_id NULL). Encrypted with
-- APP_SECRET_KEY (security.SecretCipher); key_hint (the last characters) lets a key be recognised.
CREATE TABLE provider_key
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  BIGINT      REFERENCES tenant (id) ON DELETE CASCADE,
    provider   TEXT        NOT NULL CHECK (provider IN ('ANTHROPIC', 'OPENAI', 'GEMINI')),
    api_key    TEXT        NOT NULL,
    key_hint   TEXT        NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);
CREATE UNIQUE INDEX provider_key_tenant_provider_uq ON provider_key (tenant_id, provider) WHERE tenant_id IS NOT NULL;
CREATE UNIQUE INDEX provider_key_global_provider_uq ON provider_key (provider) WHERE tenant_id IS NULL;

-- One row per model call: what it used and what it costs at the price of that moment. Calls with the admin's keys
-- (key_source GLOBAL) are billed to the tenant; the others are the tenant's own overview. Model and user are kept as
-- they were - the row must not change when a model or user is changed or deleted later.
CREATE TABLE usage_record
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT         NOT NULL REFERENCES tenant (id) ON DELETE CASCADE,
    user_id       BIGINT,
    provider      TEXT           NOT NULL,
    model_name    TEXT           NOT NULL,
    kind          TEXT           NOT NULL,
    key_source    TEXT           NOT NULL CHECK (key_source IN ('OWN', 'GLOBAL')),
    input_tokens  INTEGER        NOT NULL,
    output_tokens INTEGER        NOT NULL,
    -- The provider reported no token count (some embedding APIs): estimated from the text length.
    estimated     BOOLEAN        NOT NULL,
    amount        NUMERIC(14, 6) NOT NULL,
    created_at    TIMESTAMPTZ    NOT NULL
);
CREATE INDEX usage_record_tenant_created_idx ON usage_record (tenant_id, created_at);

-- The models a tenant may use, assigned by the admin (docs/architecture/ai-features.md "Model access"): a tenant sees,
-- chooses and calls only these - with its own key or the admin's. A new tenant has none.
CREATE TABLE tenant_model
(
    tenant_id BIGINT NOT NULL REFERENCES tenant (id) ON DELETE CASCADE,
    model_id  BIGINT NOT NULL REFERENCES ai_model (id) ON DELETE CASCADE,
    PRIMARY KEY (tenant_id, model_id)
);
CREATE INDEX tenant_model_model_idx ON tenant_model (model_id);

-- A tenant's own look (docs/architecture/branding.md): its name, primary colour and logo in the tenant area (/app) -
-- set by the admin only. A column left NULL means the installation's default (app.branding.*). The logo itself is in
-- the file storage (tenants/<id>/branding/logo); logo_type is its media type, NULL without a logo.
CREATE TABLE tenant_branding
(
    tenant_id     BIGINT PRIMARY KEY REFERENCES tenant (id) ON DELETE CASCADE,
    name          TEXT,
    primary_color TEXT CHECK (primary_color ~ '^#[0-9a-f]{6}$'),
    logo_type     TEXT CHECK (logo_type IN ('image/png', 'image/jpeg', 'image/webp')),
    updated_at    TIMESTAMPTZ NOT NULL
);

-- How a tenant's assistant answers (docs/architecture/ai-features.md "Assistant settings and templates"), kept by its
-- tenant admins and the admin. No row: the defaults. instructions go into every question's system prompt; the rest are
-- the defaults a template may override.
CREATE TABLE tenant_assistant
(
    tenant_id      BIGINT PRIMARY KEY REFERENCES tenant (id) ON DELETE CASCADE,
    instructions   TEXT        NOT NULL DEFAULT '',
    answer_source  TEXT        NOT NULL CHECK (answer_source IN ('DOCUMENTS_ONLY', 'DOCUMENTS_FIRST')),
    creativity     TEXT        NOT NULL CHECK (creativity IN ('LOW', 'MEDIUM', 'HIGH')),
    reasoning      TEXT        NOT NULL CHECK (reasoning IN ('OFF', 'LOW', 'MEDIUM', 'HIGH')),
    search_results INTEGER     NOT NULL CHECK (search_results BETWEEN 3 AND 20),
    -- The chat model of the questions that choose none - those of the MCP server (Claude Code); NULL: none chosen.
    default_model_id BIGINT REFERENCES ai_model (id) ON DELETE SET NULL,
    updated_at     TIMESTAMPTZ NOT NULL
);

-- A template a tenant's users choose in the chat ("Trainingsplaner", "Nachschlagen"): its own instructions next to the
-- tenant's, and settings of its own - NULL takes the tenant's.
CREATE TABLE chat_template
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      BIGINT      NOT NULL REFERENCES tenant (id) ON DELETE CASCADE,
    name           TEXT        NOT NULL,
    instructions   TEXT        NOT NULL DEFAULT '',
    answer_source  TEXT CHECK (answer_source IN ('DOCUMENTS_ONLY', 'DOCUMENTS_FIRST')),
    creativity     TEXT CHECK (creativity IN ('LOW', 'MEDIUM', 'HIGH')),
    reasoning      TEXT CHECK (reasoning IN ('OFF', 'LOW', 'MEDIUM', 'HIGH')),
    search_results INTEGER CHECK (search_results BETWEEN 3 AND 20),
    created_at     TIMESTAMPTZ NOT NULL,
    updated_at     TIMESTAMPTZ NOT NULL
);
CREATE UNIQUE INDEX chat_template_tenant_name_ci_uq ON chat_template (tenant_id, LOWER(name));


-- The tenant's own software connected through its MCP server (docs/architecture/mcp.md "MCP clients"): entered by its
-- tenant admins or the admin - address and, if the server asks for one, its key (encrypted with APP_SECRET_KEY, never
-- sent out again: key_hint shows its last characters).
CREATE TABLE mcp_connection
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       BIGINT      NOT NULL REFERENCES tenant (id) ON DELETE CASCADE,
    name            TEXT        NOT NULL,
    base_url        TEXT        NOT NULL,
    api_key         TEXT,
    key_hint        TEXT,
    -- When the server's tools were read last.
    tools_loaded_at TIMESTAMPTZ,
    -- Whether questions over the tenant's MCP server (its MCP key, no user) may use its reading tools - off until a
    -- tenant admin turns it on; its changing tools never (docs/architecture/mcp.md).
    mcp_server_reads BOOLEAN    NOT NULL DEFAULT FALSE,
    -- Whether the tenant's client software (/api/v1/chat with an API key, no user) may use its reading tools - off
    -- until a tenant admin turns it on; its changing tools never (docs/architecture/mcp.md).
    client_software_reads BOOLEAN NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL,
    CHECK ((api_key IS NULL) = (key_hint IS NULL))
);
CREATE UNIQUE INDEX mcp_connection_tenant_name_ci_uq ON mcp_connection (tenant_id, LOWER(name));

-- A tool the connected software offers, as read from it (tools/list). It stays off until a tenant admin turns it on;
-- changes: it changes something there (no readOnlyHint, or corrected by the admin) - asked before every call.
-- offered: the server still lists it (a tool it dropped is kept off, not deleted, so the admin's choice survives).
-- read_only_hint: what the server said when it was last read - a reload takes the server's word for changes only when
-- that hint changed (a software update made a reading tool a changing one), and keeps the admin's correction else.
CREATE TABLE mcp_tool
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    connection_id BIGINT  NOT NULL REFERENCES mcp_connection (id) ON DELETE CASCADE,
    name          TEXT    NOT NULL,
    description   TEXT    NOT NULL DEFAULT '',
    -- The tool's input JSON schema, as the server gave it.
    input_schema  TEXT    NOT NULL,
    changes        BOOLEAN NOT NULL,
    read_only_hint BOOLEAN NOT NULL,
    enabled        BOOLEAN NOT NULL DEFAULT FALSE,
    offered        BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX mcp_tool_connection_name_uq ON mcp_tool (connection_id, name);

-- Which tenant user may use which connected software in the chat: READ - its reading tools that are turned on; WRITE -
-- all its tools that are turned on. No row: no access. The client software and the MCP key never get them.
CREATE TABLE mcp_access
(
    user_id       BIGINT NOT NULL REFERENCES tenant_user (id) ON DELETE CASCADE,
    connection_id BIGINT NOT NULL REFERENCES mcp_connection (id) ON DELETE CASCADE,
    level         TEXT   NOT NULL CHECK (level IN ('READ', 'WRITE')),
    PRIMARY KEY (user_id, connection_id)
);
CREATE INDEX mcp_access_connection_idx ON mcp_access (connection_id);
