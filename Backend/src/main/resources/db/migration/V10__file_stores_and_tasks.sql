-- The tenants' file stores (docs/architecture/file-stores.md): servers the app reads files from and writes files to on
-- the tenant's behalf - SFTP and FTPS today, S3, Dropbox and SharePoint later. Kept by the tenant admins and the admin.
CREATE TABLE file_store
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT      NOT NULL REFERENCES tenant (id) ON DELETE CASCADE,
    name        TEXT        NOT NULL,
    type        TEXT        NOT NULL CHECK (type IN ('SFTP', 'FTPS')),
    -- What the type needs that is no secret, as JSON (SFTP and FTPS: host, port, username, base path, the fingerprint
    -- of the server's key or certificate a tenant admin confirmed).
    settings    TEXT        NOT NULL,
    -- The secret (the password), encrypted (security.SecretCipher) - never sent out.
    secret      TEXT        NOT NULL,
    -- The last check: when, and the error code it ended with (null: it worked).
    checked_at  TIMESTAMPTZ,
    check_error TEXT,
    created_at  TIMESTAMPTZ NOT NULL,
    updated_at  TIMESTAMPTZ NOT NULL
);

CREATE UNIQUE INDEX file_store_tenant_name_ci_uq ON file_store (tenant_id, LOWER(name));

-- Scheduled tasks (docs/architecture/tasks.md): kept by the tenant admins and the admin. Whether a tenant may have
-- them at all is the admin's switch - off for every tenant until the admin turns it on.
ALTER TABLE tenant ADD COLUMN tasks_allowed BOOLEAN NOT NULL DEFAULT false;

-- A task as its tenant admin wrote it (source: YAML or JSON, comments kept) and as the engine runs it (definition:
-- the compiled JSON, names resolved to ids). An invalid task is never stored. Its runs live in the tenant database.
CREATE TABLE task (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT      NOT NULL REFERENCES tenant (id) ON DELETE CASCADE,
    name        TEXT        NOT NULL,
    source      TEXT        NOT NULL,
    definition  TEXT        NOT NULL,
    -- Raised by every save; a run keeps the version (and the definition) it ran with.
    version     INT         NOT NULL,
    active      BOOLEAN     NOT NULL,
    -- When its schedule is due next (null: no schedule, or switched off).
    next_run_at TIMESTAMPTZ,
    -- Whether the tenant's MCP server may start it.
    open_to_mcp BOOLEAN     NOT NULL DEFAULT false,
    created_at  TIMESTAMPTZ NOT NULL,
    updated_at  TIMESTAMPTZ NOT NULL
);

CREATE UNIQUE INDEX task_tenant_name_ci_uq ON task (tenant_id, LOWER(name));
CREATE INDEX task_next_run_idx ON task (next_run_at) WHERE next_run_at IS NOT NULL;

-- The file stores a task reads, written from its definition on every save: a store in use cannot be deleted. Checked
-- at the commit, not at once: deleting a tenant cascades to its tasks and its stores in one statement, which RESTRICT
-- would refuse while a task reads a store.
CREATE TABLE task_file_store (
    task_id       BIGINT NOT NULL REFERENCES task (id) ON DELETE CASCADE,
    file_store_id BIGINT NOT NULL REFERENCES file_store (id) DEFERRABLE INITIALLY DEFERRED,
    PRIMARY KEY (task_id, file_store_id)
);

CREATE INDEX task_file_store_store_idx ON task_file_store (file_store_id);

-- The tasks the client software may start with an API key - assigned on the key, like its knowledge areas.
CREATE TABLE tenant_api_key_task (
    api_key_id BIGINT NOT NULL REFERENCES tenant_api_key (id) ON DELETE CASCADE,
    task_id    BIGINT NOT NULL REFERENCES task (id) ON DELETE CASCADE,
    PRIMARY KEY (api_key_id, task_id)
);

CREATE INDEX tenant_api_key_task_task_idx ON tenant_api_key_task (task_id);
