-- The one migration of the tenant databases for release 2.0.0: its blocks were separate migrations while 2.0.0 was
-- worked on and are folded here before the release (nothing of it was released).

-- The rows an extract step of a scheduled task gave (docs/architecture/tasks.md "extract", roadmap point 50): one per
-- document - the fields' values as JSON, the document's source (its path and the checksum of its content), and why the
-- row is unclear. Kept with its run and deleted with it, like the run's files.
CREATE TABLE task_run_row (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id  BIGINT NOT NULL REFERENCES task_run (id) ON DELETE CASCADE,
    step_id TEXT   NOT NULL,
    source  TEXT   NOT NULL,
    "values" TEXT  NOT NULL,
    unclear TEXT
);

CREATE INDEX task_run_row_run_idx ON task_run_row (run_id, id);

-- The connected software (topics) a conversation's questions leave out (docs/architecture/mcp.md "MCP clients",
-- roadmap point 51): written with every question that names the list, returned with the conversation. NULL: none.
ALTER TABLE conversation ADD COLUMN excluded_connection_ids BIGINT[];

-- A conversation answered by the tenant's A2A agent (docs/architecture/a2a.md): the agent's context it goes on in, and
-- the task waiting for the user's answer to the agent's question back. NULL: none.
ALTER TABLE conversation ADD COLUMN a2a_context_id TEXT;
ALTER TABLE conversation ADD COLUMN a2a_task_id TEXT;
-- The agent's skills a conversation's questions leave out (docs/architecture/a2a.md "The skills' choice"). NULL: none.
ALTER TABLE conversation ADD COLUMN excluded_skill_ids TEXT[];
-- An answer that is the agent's question back - the chat marks it "waiting for your answer".
ALTER TABLE message ADD COLUMN a2a_waiting BOOLEAN NOT NULL DEFAULT false;

-- The A2A tasks of the tenant's assistant (docs/architecture/a2a.md "Tasks"): a streamed or returnImmediately question,
-- or a run of a scheduled task started over A2A - owned by the MCP key that started it, stored as the SDK's JSON (its
-- answer and files included; never the question), deleted after app.a2a.task-retention-hours.
CREATE TABLE a2a_task (
    id         TEXT        PRIMARY KEY,
    mcp_key_id BIGINT      NOT NULL,
    state      TEXT        NOT NULL,
    context_id TEXT,
    run_id     BIGINT,
    task       TEXT        NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX a2a_task_key_idx ON a2a_task (mcp_key_id, updated_at);

-- The webhooks a client registered for an A2A task (docs/architecture/a2a.md "Push notifications"): the SDK's config as
-- JSON, encrypted (its token and credentials are the client's secrets) - deleted with the task.
CREATE TABLE a2a_push_config (
    task_id    TEXT        NOT NULL REFERENCES a2a_task (id) ON DELETE CASCADE,
    id         TEXT        NOT NULL,
    config     TEXT        NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (task_id, id)
);
