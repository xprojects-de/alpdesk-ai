-- The handbook (docs/architecture/doc-sites.md): one static website per scope - the whole tenant (area_id NULL) or one
-- knowledge area of the management database (no foreign key across databases, like document.area_id). Its files live
-- in the file storage below storage_prefix; a new upload writes a new prefix and swaps it here in one statement.
CREATE TABLE doc_site (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_id        BIGINT,
    storage_prefix TEXT        NOT NULL,
    file_count     INT         NOT NULL,
    size_bytes     BIGINT      NOT NULL,
    uploaded_at    TIMESTAMPTZ NOT NULL
);

CREATE UNIQUE INDEX doc_site_scope ON doc_site ((COALESCE(area_id, 0)));
