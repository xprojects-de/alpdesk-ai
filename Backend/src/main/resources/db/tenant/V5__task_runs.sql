-- The runs of the tenant's scheduled tasks (docs/architecture/tasks.md). The task itself lives in the management
-- database - task_id has no foreign key across databases (like pending_action.connection_id); deleting a task deletes
-- its rows here through the service.
CREATE TABLE task_run (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id          BIGINT      NOT NULL,
    task_version     INT         NOT NULL,
    -- The compiled definition it ran with: a later save does not change what a stored run shows.
    definition       TEXT        NOT NULL,
    state            TEXT        NOT NULL CHECK (state IN ('QUEUED', 'RUNNING', 'DONE', 'UNCLEAR', 'FAILED', 'CANCELLED')),
    started_by       TEXT        NOT NULL,
    started_by_user  BIGINT,
    -- The client software's API key that started it (no foreign key across databases - deleting the key keeps its runs).
    started_by_key   BIGINT,
    -- Cancelled: marked, then ended before its next step or round (state CANCELLED).
    cancel_requested BOOLEAN     NOT NULL DEFAULT false,
    error_code       TEXT,
    error_message    TEXT,
    mail_failed      BOOLEAN     NOT NULL DEFAULT false,
    input_tokens     BIGINT      NOT NULL DEFAULT 0,
    output_tokens    BIGINT      NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ NOT NULL,
    started_at       TIMESTAMPTZ,
    ended_at         TIMESTAMPTZ
);

CREATE INDEX task_run_task_idx ON task_run (task_id, id DESC);
-- One run of a task at a time: a second start fails here, not at a check before the insert.
CREATE UNIQUE INDEX task_run_one_open_uq ON task_run (task_id) WHERE state IN ('QUEUED', 'RUNNING');

-- What each step of a run did; a step an edge back runs again gets a row per round.
CREATE TABLE task_run_step (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id        BIGINT      NOT NULL REFERENCES task_run (id) ON DELETE CASCADE,
    step_id       TEXT        NOT NULL,
    round         INT         NOT NULL,
    state         TEXT        NOT NULL CHECK (state IN ('DONE', 'SKIPPED', 'FAILED')),
    result        TEXT,
    error_code    TEXT,
    input_tokens  BIGINT      NOT NULL DEFAULT 0,
    output_tokens BIGINT      NOT NULL DEFAULT 0,
    started_at    TIMESTAMPTZ NOT NULL,
    ended_at      TIMESTAMPTZ NOT NULL,
    UNIQUE (run_id, step_id, round)
);

-- The lines a read_files step kept of one file, "<line number>\t<text>" per line - the steps after it read these,
-- the graph's state only their ids.
CREATE TABLE task_run_file (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id  BIGINT NOT NULL REFERENCES task_run (id) ON DELETE CASCADE,
    step_id TEXT   NOT NULL,
    name    TEXT   NOT NULL,
    lines   TEXT   NOT NULL
);

CREATE INDEX task_run_file_run_idx ON task_run_file (run_id);

-- How far a task has read each file of a store; moved on only after a successful run.
CREATE TABLE task_read_position (
    task_id     BIGINT      NOT NULL,
    store_id    BIGINT      NOT NULL,
    path        TEXT        NOT NULL,
    byte_offset BIGINT      NOT NULL,
    line_number BIGINT      NOT NULL,
    modified_at TIMESTAMPTZ,
    PRIMARY KEY (task_id, store_id, path)
);

-- langgraph4j's checkpoints (its PostgresSaver 1.9.6, schema v1.1, created here instead of by the saver: createTables(false)).
-- Deleted at the end of every run.
CREATE TABLE IF NOT EXISTS lg4jthread (
    thread_id   UUID PRIMARY KEY,
    thread_name VARCHAR(255),
    is_released BOOLEAN DEFAULT FALSE NOT NULL
);

CREATE TABLE IF NOT EXISTS lg4jcheckpoint (
    checkpoint_id        UUID PRIMARY KEY,
    parent_checkpoint_id UUID,
    thread_id            UUID         NOT NULL REFERENCES lg4jthread (thread_id) ON DELETE CASCADE,
    node_id              VARCHAR(255),
    next_node_id         VARCHAR(255),
    state_data           TEXT         NOT NULL,
    state_content_type   VARCHAR(100) NOT NULL,
    saved_at             TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_lg4jcheckpoint_thread_id ON lg4jcheckpoint (thread_id);
CREATE INDEX IF NOT EXISTS idx_lg4jcheckpoint_thread_id_saved_at_desc ON lg4jcheckpoint (thread_id, saved_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS idx_unique_lg4jthread_thread_name_unreleased ON lg4jthread (thread_name)
    WHERE is_released = FALSE;
