-- Initial schema of every tenant's own database (docs/architecture/tenancy.md), migrated by
-- services.tenant.TenantDatabases when the tenant is created and on every start. Every later schema change is a new
-- V<n>__<description>.sql file (until the first production installation this file may still be extended).
--
-- The embeddings of the documents' chunks are in the table "embedding", created by langchain4j's
-- PgVectorEmbeddingStore with the vector length of the tenant's embedding model (it is dropped and filled again when
-- that model changes).
CREATE EXTENSION IF NOT EXISTS vector;

-- The company's knowledge (docs/architecture/ai-features.md "Documents and embeddings"): uploaded by an admin or the
-- client software, found in the chat by every user. Its text is kept, so it can be embedded again with another model
-- without uploading it again.
CREATE TABLE document
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name    TEXT        NOT NULL,
    -- The folder it came from in an imported ZIP archive ("Lehrgang/Referate"); '' for a single upload.
    folder       TEXT        NOT NULL DEFAULT '',
    content_type TEXT,
    size_bytes   BIGINT      NOT NULL,
    -- Tika's text; for a document with images or scans the image model's reading replaces it while it is embedded.
    text         TEXT        NOT NULL,
    -- Whether its images or scanned pages are read by the image model before it is embedded - the original file is
    -- kept in the file storage for that (docs/architecture/ai-features.md "Images and scans").
    reads_images BOOLEAN     NOT NULL DEFAULT FALSE,
    status       TEXT        NOT NULL CHECK (status IN ('PENDING', 'PROCESSING', 'READY', 'FAILED')),
    error        TEXT,
    chunk_count  INTEGER     NOT NULL DEFAULT 0,
    -- The tenant admin who uploaded it (the management database's tenant_user.id - no foreign key across databases);
    -- NULL for the admin and the client software.
    uploaded_by  BIGINT,
    -- Where it comes from (docs/architecture/ai-features.md "Documents pushed by the client software"): an upload
    -- (single or ZIP) or the client software. A known external_id replaces that document instead of adding a second
    -- one - the client software's own key, or the path inside a ZIP archive.
    origin       TEXT        NOT NULL CHECK (origin IN ('UPLOAD', 'API')),
    external_id  TEXT,
    -- SHA-256 of the extracted text - of the file itself when the image model reads it: an unchanged document is not
    -- embedded again, and the same content under another name is embedded once.
    content_hash TEXT,
    created_at   TIMESTAMPTZ NOT NULL,
    updated_at   TIMESTAMPTZ NOT NULL
);
-- A key is unique per origin: the sources of roadmap point 8 bring keys of their own.
CREATE UNIQUE INDEX document_external_id_uq ON document (origin, external_id) WHERE external_id IS NOT NULL;
CREATE INDEX document_content_hash_idx ON document (content_hash);

-- A conversation belongs to the user who had it - other users of the tenant do not see it. The client software's
-- conversations (/api/v1/chat) have no user (user_id NULL): they are seen through the tenant API only.
CREATE TABLE conversation
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT,
    title       TEXT        NOT NULL,
    -- The template of its last question (the management database's chat_template.id - no foreign key across
    -- databases); NULL for the tenant's settings alone. The chat shows it chosen again.
    template_id BIGINT,
    created_at  TIMESTAMPTZ NOT NULL,
    updated_at  TIMESTAMPTZ NOT NULL
);
CREATE INDEX conversation_user_idx ON conversation (user_id, updated_at);

CREATE TABLE message
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT      NOT NULL REFERENCES conversation (id) ON DELETE CASCADE,
    role            TEXT        NOT NULL CHECK (role IN ('USER', 'ASSISTANT')),
    content         TEXT        NOT NULL,
    -- The model that answered (display name as it was), NULL for the user's messages.
    model_name      TEXT,
    created_at      TIMESTAMPTZ NOT NULL
);
CREATE INDEX message_conversation_idx ON message (conversation_id, id);

-- The files of a conversation (docs/architecture/ai-features.md "Files in the chat"): uploaded by its user or the
-- client software, or created by the model (tool create_file). They are not embedded - every question of the
-- conversation is sent with them. The content lives in the file storage (app.storage.*) under storage_dir; deleting the
-- conversation deletes them.
CREATE TABLE conversation_file
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT      NOT NULL REFERENCES conversation (id) ON DELETE CASCADE,
    -- The answer that created a generated file; NULL for an uploaded one.
    message_id      BIGINT REFERENCES message (id) ON DELETE CASCADE,
    origin          TEXT        NOT NULL CHECK (origin IN ('UPLOADED', 'GENERATED')),
    file_name       TEXT        NOT NULL,
    content_type    TEXT        NOT NULL,
    size_bytes      BIGINT      NOT NULL,
    -- The file's "directory" in the file storage: the file itself under <storage_dir>file, images under <storage_dir>image-<n>.
    storage_dir     TEXT        NOT NULL,
    -- The text the model reads (extracted on upload, the written content of a generated file); NULL for images.
    text            TEXT,
    -- How many images the model is sent: an uploaded image, the pages of a scanned PDF.
    image_count     INTEGER     NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ NOT NULL
);
CREATE INDEX conversation_file_conversation_idx ON conversation_file (conversation_id, id);
-- Deleting a conversation deletes its messages; without it each one would scan the tenant's files for its own.
CREATE INDEX conversation_file_message_idx ON conversation_file (message_id);

-- A changing tool call of the company's connected software, waiting for the user (docs/architecture/mcp.md "Changing
-- tools"): the answer that asked for it stops there, the chat shows the call, and the user runs or cancels it - then
-- the model goes on with the software's answer or the refusal. It expires after a day, or when a new question comes.
CREATE TABLE pending_action
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT      NOT NULL REFERENCES conversation (id) ON DELETE CASCADE,
    -- The answer that asked for it.
    message_id      BIGINT      NOT NULL REFERENCES message (id) ON DELETE CASCADE,
    -- The management database's ai_model.id (the model that goes on), mcp_connection.id and mcp_tool.id - no foreign
    -- keys across databases.
    model_id        BIGINT      NOT NULL,
    connection_id   BIGINT      NOT NULL,
    tool_id         BIGINT      NOT NULL,
    -- As the user saw them: the software's and the tool's names.
    software_name   TEXT        NOT NULL,
    tool_name       TEXT        NOT NULL,
    -- The model's call: its id, the name it called ("<software>__<tool>") and its arguments (a JSON object).
    call_id         TEXT        NOT NULL,
    called_name     TEXT        NOT NULL,
    arguments       TEXT        NOT NULL,
    status          TEXT        NOT NULL CHECK (status IN ('PENDING', 'RUN', 'CANCELLED', 'EXPIRED')),
    -- What the software answered when it was run.
    result          TEXT,
    created_at      TIMESTAMPTZ NOT NULL,
    decided_at      TIMESTAMPTZ
);
CREATE INDEX pending_action_conversation_idx ON pending_action (conversation_id);
CREATE INDEX pending_action_message_idx ON pending_action (message_id);
